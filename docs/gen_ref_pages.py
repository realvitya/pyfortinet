"""Generate API Markdown before running Zensical, preserving published URLs."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "<!-- Generated by docs/gen_ref_pages.py; do not edit. -->\n\n"


def generate_reference(project_root: Path = ROOT) -> None:
    """Write reference pages and navigation; remove only stale generated Markdown."""
    project_root = project_root.resolve()
    source = project_root / "pyfortinet"
    reference = project_root / "docs" / "reference"
    if not source.is_dir():
        raise ValueError(f"Missing Python source directory: {source}")
    if reference.resolve() != reference:
        raise ValueError("The generated reference directory must not use symlinks")

    pages = {}
    summary = []
    for path in sorted(source.rglob("*.py")):
        if not path.resolve().is_relative_to(source) or path.is_symlink():
            continue
        module = path.relative_to(source).with_suffix("")
        parts = list(module.parts)
        if parts[-1] == "__init__":
            parts = parts[:-1]
        elif parts[-1] == "__main__":
            continue
        if not parts:
            continue

        doc_path = module.with_suffix(".md")
        pages[reference / doc_path] = "::: " + ".".join(parts) + "\n"
        summary.append("    " * (len(parts) - 1) + f"- [{parts[-1]}]({doc_path.as_posix()})\n")
    pages[reference / "SUMMARY.md"] = "".join(summary)

    # Check all existing output before writing or removing anything. This directory
    # belongs to the generator, but unrelated files must never be overwritten.
    existing = set(reference.rglob("*.md"))
    for path in existing | pages.keys():
        if path.is_symlink() or not path.resolve().is_relative_to(reference):
            raise ValueError(f"Reference output must stay inside {reference}: {path}")
        if path.exists() and not path.read_text(encoding="utf-8").startswith(GENERATED):
            raise ValueError(f"Refusing to replace non-generated reference page: {path}")

    for path, content in pages.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(GENERATED + content, encoding="utf-8")
    for path in existing - pages.keys():
        path.unlink()


if __name__ == "__main__":
    generate_reference()
